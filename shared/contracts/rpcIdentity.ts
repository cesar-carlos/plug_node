import type { JsonRpcId } from "./api";
import { PlugValidationError } from "./errors";
import { isRecord } from "../utils/json";

/** Older correlated envelopes omit IDs, and some hubs stringify numeric IDs. */
export const assertRpcResponseIdentity = (
  response: unknown,
  commands: { readonly id?: JsonRpcId } | readonly { readonly id?: JsonRpcId }[],
  hubRequestId?: string,
): void => {
  const expected = Array.isArray(commands) ? commands : [commands];
  const items = Array.isArray(response)
    ? response
    : isRecord(response) && response.type === "batch" && Array.isArray(response.items)
      ? response.items
      : [isRecord(response) && response.type === "single" ? response.item : response];
  // Null IDs are notifications; omitted request IDs are generated by the Hub.
  // Count legacy replies without inner IDs as well, before checking known IDs.
  if (
    Array.isArray(commands) &&
    items.length !== expected.filter((command) => command.id !== null).length
  ) {
    throw new PlugValidationError(
      "RPC response identity is incomplete or has unexpected batch items.",
    );
  }
  // REST may delegate ID generation to the hub when the request omits it.
  if (expected.some((command) => command.id === undefined)) return;
  const ids = new Set(
    expected
      .filter((command) => command.id !== null)
      .map((command) => String(command.id)),
  );
  if (expected.length === 1 && hubRequestId !== undefined) ids.add(hubRequestId);
  const seen = new Set<string>();
  for (const item of items) {
    if (!isRecord(item) || item.id === undefined) continue;
    const id = item.id;
    if (
      (typeof id !== "string" && typeof id !== "number") ||
      (typeof id === "number" && !Number.isFinite(id)) ||
      !ids.has(String(id)) ||
      seen.has(String(id))
    ) {
      throw new PlugValidationError(
        "RPC response identity does not match the dispatched command.",
      );
    }
    seen.add(String(id));
  }
};

export const assertResponseAgentIdentity = (response: unknown, agentId: string): void => {
  if (
    isRecord(response) &&
    response.agentId !== undefined &&
    response.agentId !== agentId
  ) {
    throw new PlugValidationError(
      "Response agent identity does not match the dispatched agent.",
    );
  }
};

/** Notification acknowledgements cannot substitute for command results. */
export const assertRpcResponseType = (
  notification: boolean,
  commands: { readonly id?: JsonRpcId } | readonly { readonly id?: JsonRpcId }[],
): void => {
  const expected = Array.isArray(commands) ? commands : [commands];
  if (notification && expected.some((command) => command.id !== null)) {
    throw new PlugValidationError(
      "RPC response type does not match the dispatched command: expected a result, received a notification acknowledgement.",
    );
  }
};
